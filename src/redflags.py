def detect(text: str) -> List[str]:
    """Вернуть список красных флагов, найденных в реплике."""
    found = []
    for flag, regexes in COMPILED.items():
        if any(r.search(text) for r in regexes):
            found.append(flag)
    return found


def risk_from_flags(flags: List[str]) -> float:
    """
    Агрегировать флаги в риск через noisy-OR:
        1 - Π(1 - w_i)
    Несколько слабых флагов вместе дают больше, чем каждый по отдельности,
    но риск никогда не достигает единицы.
    """
    p = 1.0
    for f in flags:
        p *= (1.0 - WEIGHTS.get(f, 0.5))
    return round(1.0 - p, 4)


def explain(flags: List[str]) -> List[str]:
    """Человекочитаемое объяснение для интерфейса."""
    return [EXPLAIN_RU.get(f, f) for f in flags]


class RuleBaseline:
    """
    Бейзлайн: накопительный риск по красным флагам с порогом.
    Обученная модель обязана его превзойти — особенно по false positive rate
    на трудных негативах и по раннему срабатыванию.
    """

    def __init__(self, threshold: float = 0.8, decay: float = 0.9):
        self.threshold = threshold
        self.decay = decay

    def score_dialogue(self, turns: List[dict]) -> List[float]:
        """Вернуть накопительный риск после каждой реплики."""
        scores, running = [], 0.0
        for t in turns:
            flags = detect(t["text"])
            turn_risk = risk_from_flags(flags)
            running = max(turn_risk, running * self.decay)
            scores.append(round(running, 4))
        return scores

    def first_alert_index(self, turns: List[dict]) -> int:
        """Индекс первой реплики, где риск превысил порог. -1 если не сработал."""
        for i, s in enumerate(self.score_dialogue(turns)):
            if s >= self.threshold:
                return i
        return -1


